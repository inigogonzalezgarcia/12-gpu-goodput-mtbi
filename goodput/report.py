from goodput.analyze import CATEGORIES, WASTE, Summary, SLOResult
from goodput.experiments import Result, Sweep

LABELS = {"productive": "Productive", "checkpoint": "Checkpoint writes", "lost": "Lost work",
          "detect": "Detection", "wait": "Waiting for nodes", "restart": "Restart"}


def pct(x: float, digits: int = 1) -> str:
    return f"{x * 100:.{digits}f}%"


# --- analysis of one event log -------------------------------------------------------------------

def summary_text(s: Summary, slo_res: SLOResult | None = None, top: int = 5) -> str:
    lines = [f"Jobs: {s.jobs}, GPUs: {s.gpus}, wall-clock: {s.wall_hours:.1f} h, GPU-hours: {s.total_gpu_hours:,.0f}",
             f"Goodput: {pct(s.goodput)}",
             f"Interruptions: {s.interruptions}  MTBI: {_h(s.mtbi_hours)}  node MTBF (estimated): {_h(s.node_mtbf_hours)}",
             "", "Where the GPU-hours went:"]
    for c in CATEGORIES:
        lines.append(f"  {LABELS[c]:<18} {s.gpu_hours[c]:>12,.0f}  {pct(_share(s, c)):>6}")
    lines += ["", "Cost per interruption cause (lost work + detection + waiting + restart):"]
    for cause, d in sorted(s.by_cause.items(), key=lambda kv: -kv[1]["gpu_hours"]):
        lines.append(f"  {cause:<18} {d['count']:>4} x  {d['gpu_hours']:>10,.0f} GPU-h")
    if s.nodes:
        lines += ["", f"Nodes with the most interruptions (top {top}):"]
        lines += [f"  {n:<10} {k}" for n, k in s.nodes.most_common(top)]
    if slo_res:
        lines += ["", f"Goodput SLO {pct(slo_res.target, 0)} per {slo_res.window_hours:g} h window: "
                      f"met in {slo_res.met} of {len(slo_res.rows)}"]
        for r in slo_res.rows:
            lines.append(f"  {r['start']:%Y-%m-%d} {pct(r['goodput']):>6}  budget burn {pct(r['budget_burn'], 0):>5}  "
                         f"{r['interruptions']:>3} interruptions  top waste: {r['top_waste']}")
    return "\n".join(lines)


def summary_json(s: Summary, slo_res: SLOResult | None = None) -> str:
    d = {"jobs": s.jobs, "gpus": s.gpus, "wall_hours": round(s.wall_hours, 3), "goodput": round(s.goodput, 5),
         "interruptions": s.interruptions, "mtbi_hours": _r(s.mtbi_hours), "node_mtbf_hours": _r(s.node_mtbf_hours),
         "gpu_hours": {c: round(v, 1) for c, v in s.gpu_hours.items()},
         "by_cause": {k: {"count": v["count"], "gpu_hours": round(v["gpu_hours"], 1)} for k, v in s.by_cause.items()},
         "top_nodes": s.nodes.most_common(10)}
    if slo_res:
        d["slo"] = {"target": slo_res.target, "window_hours": slo_res.window_hours, "met": slo_res.met,
                    "windows": [{**r, "start": r["start"].isoformat(), "end": r["end"].isoformat(),
                                 "goodput": round(r["goodput"], 5), "budget_burn": round(r["budget_burn"], 4)}
                                for r in slo_res.rows]}
    return json.dumps(d, indent=2)


# --- experiments ---------------------------------------------------------------------------------

def results_markdown(results: list[Result], sw: Sweep) -> str:
    base = results[0].mean
    out = [f"<!-- generated by `goodput report`: {results[0].seeds} seeds per scenario, "
           f"{results[0].scenario.days:g} days each. Do not edit by hand; CI checks it is up to date. -->", "",
           "### Scenarios", "",
           "| Scenario | Goodput (mean) | p10–p90 | vs baseline | Interruptions / run | MTBI | Biggest waste |",
           "|---|---|---|---|---|---|---|"]
    for r in results:
        waste = max(WASTE, key=lambda c: r.shares[c])
        out.append(f"| {r.scenario.name} | {pct(r.mean)} | {pct(r.p10)}–{pct(r.p90)} | {(r.mean - base) * 100:+.1f} pp | "
                   f"{r.interruptions:.1f} | {r.mtbi_hours:.1f} h | {LABELS[waste]} ({pct(r.shares[waste])}) |")
    out += ["", "### Where the GPU-hours went (mean share)", "",
            "| Scenario | " + " | ".join(LABELS[c] for c in CATEGORIES) + " |",
            "|---|" + "---|" * len(CATEGORIES)]
    for r in results:
        out.append(f"| {r.scenario.name} | " + " | ".join(pct(r.shares[c]) for c in CATEGORIES) + " |")
    s = sw.scenario
    out += ["", f"### Checkpoint interval sweep ({s.name})", "",
            f"Job MTBI {s.nominal_mtbi_hours():.1f} h, checkpoint write {s.checkpoint_minutes:g} min. "
            f"Young: {sw.young_minutes:.0f} min, Daly: {sw.daly_minutes:.0f} min "
            f"(simulated goodput at Daly's interval: {pct(sw.daly_simulated)}). "
            f"Best interval in the sweep: {sw.best.interval_minutes:g} min ({pct(sw.best.simulated)}).", "",
            "| Interval | Simulated goodput | p10–p90 | First-order model |", "|---|---|---|---|"]
    for p in sw.points:
        out.append(f"| {p.interval_minutes:g} min | {pct(p.simulated)} | {pct(p.p10)}–{pct(p.p90)} | {pct(p.model)} |")
    return "\n".join(out) + "\n"


